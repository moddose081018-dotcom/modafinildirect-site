#!/usr/bin/env node
// Builds the public artifact into dist/ from the page sources in this repo.
//
// A page is any `index.html` at the repository root or inside a directory
// that is not private. The route is the directory path with a trailing slash.
// The build also emits sitemap.xml, _build-manifest.json and the route set
// the Pages middleware uses to return hard 404s for unknown paths.
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ensureSkipLink, normalizeCanonical, normalizeHeadingHierarchy } from './html-hygiene.js';
import { SITE } from './site.config.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'dist');
const checkOnly = process.argv.includes('--check');

if (output !== join(root, 'dist') || output === root) {
  throw new Error(`Refusing to clean unexpected output path: ${output}`);
}

export const PRIVATE_SEGMENTS = new Set([
  '.claude', '.git', '.github', 'dist', 'functions', 'node_modules', 'notes', 'reports', 'tests', 'tools',
]);
const PUBLIC_ASSET_DIRECTORIES = ['assets'];
const PUBLIC_ROOT_FILES = ['404.html', '_headers', '_redirects', 'favicon.ico', 'robots.txt'];

// `_headers` serves /assets/* as immutable for a year, so every stylesheet
// and script reference is stamped with a digest of the file's own contents.
// Each version gets its own URL, which is what `immutable` is for.
const VERSIONED_ASSETS = ['/assets/css/site.css', '/assets/js/site.js'];

function assetVersions() {
  const versions = new Map();
  for (const asset of VERSIONED_ASSETS) {
    const source = join(root, asset.replace(/^\//, ''));
    if (!existsSync(source)) throw new Error(`Cannot version a missing asset: ${asset}`);
    const digest = createHash('sha256').update(readFileSync(source)).digest('hex').slice(0, 8);
    versions.set(asset, `${asset}?v=${digest}`);
  }
  return versions;
}

function versionAssets(html, versions) {
  let versioned = html;
  for (const [asset, replacement] of versions) {
    versioned = versioned.replaceAll(`${asset}"`, `${replacement}"`).replaceAll(`${asset}'`, `${replacement}'`);
  }
  return versioned;
}

function routeForIndex(relativePath) {
  const normalized = relativePath.replaceAll('\\', '/');
  if (normalized === 'index.html') return '/';
  return `/${normalized.slice(0, -'index.html'.length)}`;
}

export function collectPages() {
  const pages = [];
  (function walk(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) continue;
      const absolute = join(directory, entry.name);
      const rel = relative(root, absolute);
      const first = rel.split(sep)[0];
      if (entry.isDirectory()) {
        if (!PRIVATE_SEGMENTS.has(first) && !PUBLIC_ASSET_DIRECTORIES.includes(first)) walk(absolute);
      } else if (entry.name === 'index.html') {
        pages.push({ source: absolute, rel, route: routeForIndex(rel) });
      }
    }
  })(root);
  return pages.sort((a, b) => a.route.localeCompare(b.route));
}

// Editorial notes are kept in the source so the work queue survives, but they
// must not reach the CDN. Same rule as buymoda: grep for the marker on the
// published URL must return 0.
function stripEditorialComments(html) {
  return html.replace(/<!--[\s\S]*?-->/g, (block) => (
    /\bSHANE\b|INPUT REQUIRED|TODO|DRAFT NOTE|COMPLIANCE|HARD RULE|META TITLE|META DESC|SCHEMA NOTE/i.test(block) ? '' : block
  ));
}

function isIndexable(html) {
  return !/<meta[^>]+name=["']robots["'][^>]+content=["'][^"']*noindex/i.test(html);
}

function lastModified(html) {
  const match = html.match(/<meta[^>]+property=["']article:modified_time["'][^>]+content=["']([^"']+)["']/i)
    ?? html.match(/"dateModified"\s*:\s*"([^"]+)"/);
  return match ? match[1].slice(0, 10) : undefined;
}

export function prepareHtml(html, route, versions) {
  let prepared = stripEditorialComments(html);
  prepared = prepared.replaceAll(`${SITE.origin}/assets/`, '/assets/');
  prepared = versionAssets(prepared, versions);
  prepared = normalizeCanonical(prepared, `${SITE.origin}${route}`);
  prepared = ensureSkipLink(prepared);
  prepared = normalizeHeadingHierarchy(prepared);
  return prepared;
}

function escapeXml(value) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
}

function routesModule(routes) {
  const body = routes.map((route) => `  ${JSON.stringify(route)},`).join('\n');
  return `// Generated by tools/build-public-site.js. Do not hand-edit.\nexport const ROUTES = [\n${body}\n];\n`;
}

function main() {
  const versions = assetVersions();
  const pages = collectPages();
  const routes = pages.map((page) => page.route);
  const generated = join(root, 'functions', 'routes.generated.js');
  const expectedModule = routesModule(routes);

  if (checkOnly) {
    const current = existsSync(generated) ? readFileSync(generated, 'utf8') : '';
    if (current !== expectedModule) {
      console.error('functions/routes.generated.js is stale; run npm run build and commit it');
      process.exit(1);
    }
    console.log(`routes.generated.js is current (${routes.length} routes)`);
    return;
  }

  rmSync(output, { recursive: true, force: true });
  mkdirSync(output, { recursive: true });

  const sitemapEntries = [];
  for (const page of pages) {
    const html = readFileSync(page.source, 'utf8');
    const prepared = prepareHtml(html, page.route, versions);
    const destination = join(output, page.rel);
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, prepared);
    if (isIndexable(prepared)) sitemapEntries.push({ loc: `${SITE.origin}${page.route}`, lastmod: lastModified(prepared) });
  }

  for (const directory of PUBLIC_ASSET_DIRECTORIES) {
    if (existsSync(join(root, directory))) cpSync(join(root, directory), join(output, directory), { recursive: true });
  }
  for (const file of PUBLIC_ROOT_FILES) {
    const source = join(root, file);
    if (!existsSync(source)) continue;
    const content = file.endsWith('.html')
      ? versionAssets(stripEditorialComments(readFileSync(source, 'utf8')), versions)
      : readFileSync(source);
    writeFileSync(join(output, file), content);
  }

  const sitemap = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...sitemapEntries.map(({ loc, lastmod }) => `  <url><loc>${escapeXml(loc)}</loc>${lastmod ? `<lastmod>${lastmod}</lastmod>` : ''}</url>`),
    '</urlset>',
    '',
  ].join('\n');
  writeFileSync(join(output, 'sitemap.xml'), sitemap);

  writeFileSync(generated, expectedModule);

  const commit = process.env.SITE_COMMIT_SHA || process.env.GITHUB_SHA || 'local';
  writeFileSync(join(output, '_build-manifest.json'), `${JSON.stringify({
    site: SITE.host,
    commit,
    builtAt: new Date().toISOString(),
    routes,
  }, null, 2)}\n`);

  console.log(`Built ${pages.length} pages into dist (${sitemapEntries.length} indexable), routes written to functions/routes.generated.js`);
}

main();
